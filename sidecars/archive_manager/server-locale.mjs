export function isSupportedLanguage(value) {
  return typeof value === 'string' && Object.hasOwn(messages, value);
}

export function withRequestLocale(handler) {
  return (data) => {
    const locale = isSupportedLanguage(data?.locale) ? data.locale : DEFAULT_LANGUAGE;
    return requestLocale.run(locale, () => handler(data ?? {}));
  };
}

export function getRequestLanguage() {
  return requestLocale.getStore() ?? DEFAULT_LANGUAGE;
}

export function translateForLocale(locale, key, ...args) {
  const language = isSupportedLanguage(locale) ? locale : DEFAULT_LANGUAGE;
  const template = messages[language][key];
  return typeof template === 'function' ? template(...args) : template;
}

export function t(key, ...args) {
  return translateForLocale(getRequestLanguage(), key, ...args);
}
